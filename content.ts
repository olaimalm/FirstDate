export function forfeitFor(levelId: number): string {
  const pool = levelId <= 2 ? FORFEITS.mild : FORFEITS.spicy;
  return pool[Math.floor(Math.random() * pool.length)];
}

export type CustomCard = CardType & { id: string; levelId: number };
export type DeckCard = CardType & { custom?: boolean };

function shuffle<T>(items: T[]): T[] {
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// Shuffles a level's cards together with the couple's own cards for that level.
// The level's last card is its closing card, so it always stays last.
export function buildDeck(level: LevelType, custom: CustomCard[]): DeckCard[] {
  const closing = level.cards[level.cards.length - 1];
  const mine: DeckCard[] = custom
    .filter((c) => c.levelId === level.id)
    .map((c) => ({ type: c.type, text: c.text, custom: true }));
  return [...shuffle([...level.cards.slice(0, -1), ...mine]), closing];
}
